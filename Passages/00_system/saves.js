Save.onLoad.add(function (save) {
    if (save.version === undefined || save.version < "0.03") {
        alert("Saves older than 0.03 are no longer supported!");
        return;
    }

    let patch;

    for (const moment of save.state.history) {
        const vars = moment.variables;
        while (patch = savePatches[vars.Version]) {
            const oldv = vars.Version;
            patch(vars);
            const newv = vars.Version;
            if (oldv == newv) {
                alert(`Patch for version ${oldv} failed to update save version.`);
                return;
            }
        }
    }
    // const version = save.state.history[save.state.index].variables.Version;
    // if (version != Config.saves.version) {
    //     alert(`Config.saves.version is ${Config.saves.version}, but the patch chain ended at ${version}`);
    // }
});
